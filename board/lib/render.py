def render_html(
    *,
    season: int,
    week: int,
    rows: list[dict],
    logo_dir: Path,
    pct_by_rank: dict[int, str | None],
    show_pct: bool,
    notes: dict,
) -> tuple[str, int]:
    missing = []
    sources = {}
    for row in rows:
        path = logo_file(logo_dir, row["teamAbbr"])
        if not path.is_file():
            missing.append(row["teamAbbr"])
        else:
            sources[row["rank"]] = path.resolve().as_uri()
    if missing:
        raise MissingLogoError(sorted(set(missing)))

    max_total = max(row["total"] for row in rows)
    parts = []
    for row in rows:
        tag = notes.get(row["kicker"]) or ""
        parts.append(
            _row_html(row, sources[row["rank"]], max_total, pct_by_rank.get(row["rank"]), show_pct, tag)
        )
    row_h = 156 if show_pct else 128
    canvas_h = 1680 + 10 * (row_h - 128)
    pct_css = (
        "  .pct { font-size:24px; font-weight:600; color:#6E6E6E; line-height:1; margin:-2px 0 12px; letter-spacing:0.2px; }\n"
        if show_pct
        else ""
    )
    html = _PAGE.substitute(
        season=season,
        week=week,
        canvas_h=canvas_h,
        png_h=canvas_h * 2,
        pct_note=" · SHOW_PCT stat line" if show_pct else "",
        row_h=row_h,
        pct_css=pct_css,
        rows="\n".join(parts),
    )
    return html, canvas_h


def _map_row(kicker: dict, rank: int) -> dict:
    return {
        "rank": rank,
        "kicker": kicker["kicker"],
        "teamAbbr": kicker["teamAbbr"],
        "fg": kicker["fg"],
        "pat": kicker["pat"],
        "fgBlocked": kicker["fgBlock"],
        "patBlocked": kicker["patBlock"],
        "total": kicker["total"],
        "week": kicker["week"],
    }


def build_board(
    report: dict,
    *,
    exclusions: list[dict] | None = None,
    notes: dict | None = None,
    stats: dict | None = None,
    show_pct: bool = True,
    logo_dir: Path,
    all_misses: list[dict] | None = None,
) -> dict:
    """Select the top 10 and build the HTML, JSON summary, and suggested post.

    Kickers already flagged in the report are re-filtered here so an older
    rescan-report.json still honors kicker-exclude.json.
    """
    week = int(report["week"])
    season = int(report["seasonYear"])
    excl = exclusions if exclusions is not None else []
    notes = notes or {}
    week_index = week_index_from_misses(all_misses)
    for row in report.get("viewA_top10") or []:
        week_index.setdefault(row["kicker"], row.get("week"))

    pool = []
    for kicker in report["allKickers"]:
        enriched = dict(kicker)
        enriched["week"] = week_of(enriched, week, week_index)
        # Rank from the counts, then apply the current exclusion list.
        enriched["fgBlock"] = kicker.get("fgBlock", kicker.get("fgBlocked", 0))
        enriched["patBlock"] = kicker.get("patBlock", kicker.get("patBlocked", 0))
        pool.append(enriched)
    ranked = rank_kickers(pool, excl)
    board = select_board(ranked, 10)
    if not board:
        raise ValueError("no kickers left on the board after exclusions")

    rows = [_map_row(kicker, i) for i, kicker in enumerate(board, 1)]
    warnings: list[str] = []
    pct_by_rank: dict[int, str | None] = {}
    pct_status = "off (SHOW_PCT=0)"
    effective_show = False
    if show_pct:
        if not stats:
            warnings.append("WARN PCT_FALLBACK: cannot use ESPN kicking stats (no stats file); rendering OLD layout without percentages")
            pct_status = "fallback - old layout, stats unavailable (no stats file)"
        else:
            indexed = index_stats(stats)
            for row, kicker in zip(rows, board):
                line, warning = stat_line(
                    {**kicker, "fg": row["fg"], "pat": row["pat"]},
                    indexed,
                )
                pct_by_rank[row["rank"]] = line
                if warning:
                    warnings.append(warning)
            names = {row["rank"]: row["kicker"] for row in rows}
            effective_show, pct_status = summarize_pct(pct_by_rank, names)
            if not effective_show:
                warnings.append(
                    "WARN PCT_FALLBACK: no board kicker has ESPN stats matching board counts; "
                    "rendering OLD layout without percentages"
                )
                pct_by_rank = {}

    for row in rows:
        row["pct"] = pct_by_rank.get(row["rank"]) if effective_show else None

    html, canvas_h = render_html(
        season=season,
        week=week,
        rows=rows,
        logo_dir=logo_dir,
        pct_by_rank=pct_by_rank if effective_show else {},
        show_pct=effective_show,
        notes=notes,
    )
    post = suggested_post(season, week, rows)
    excluded_names = [kicker["kicker"] for kicker in ranked if kicker.get("excluded")]

    fitzgerald = []
    for kicker in report.get("fitzgerald") or []:
        fitzgerald.append(
            {
                "kicker": kicker["kicker"],
                "teamAbbr": kicker["teamAbbr"],
                "athleteId": kicker.get("athleteId"),
                "fg": kicker["fg"],
                "pat": kicker["pat"],
                "fgMiss": kicker.get("fgMiss"),
                "fgBlock": kicker.get("fgBlock"),
                "patMiss": kicker.get("patMiss"),
                "patBlock": kicker.get("patBlock"),
                "total": kicker["total"],
                "misses": kicker.get("misses") or [],
            }
        )

    leaders = {
        "seasonYear": season,
        "week": week,
        "tiebreak": TIEBREAK,
        "pctStatus": pct_status,
        "showPct": effective_show,
        "canvas": {"css": [1080, canvas_h], "png": [2160, canvas_h * 2]},
        "excludedKickers": excluded_names,
        "suggestedPost": post,
        "rows": rows,
    }
    all_board = {
        "seasonYear": season,
        "week": week,
        "gamesScanned": report.get("gamesScanned"),
        "totalMissPlays": report.get("totalMissPlays"),
        "uniqueKickers": report.get("uniqueKickers"),
        "detectionBreakdown": report.get("detectionBreakdown"),
        "blockedCounts": report.get("blockedCounts"),
        "boardConfirmedVsLeadersJson": True,
        "tiebreak": report.get("tiebreak") or TIEBREAK,
        "pctStatus": pct_status,
        "top10": [
            {key: row[key] for key in ("rank", "kicker", "teamAbbr", "fg", "pat", "total", "week")}
            for row in rows
        ],
        "top10WithBlockSplit": [
            {
                "rank": row["rank"],
                "kicker": row["kicker"],
                "teamAbbr": row["teamAbbr"],
                "fg": row["fg"],
                "pat": row["pat"],
                "fgBlocked": row["fgBlocked"],
                "patBlocked": row["patBlocked"],
                "total": row["total"],
                "week": row["week"],
                "pct": row["pct"],
            }
            for row in rows
        ],
        "fitzgerald": fitzgerald,
        "allKickers": [public_kicker(kicker) for kicker in ranked],
        "excludedKickers": excluded_names,
        "skippedErasedPlays": report.get("skippedErasedPlays") or [],
        "includesBlockedPAT": True,
        "includesBlockedFG": True,
        "suggestedPost": post,
    }
    return {
        "leaders": leaders,
        "all": all_board,
        "html": html,
        "post": post,
        "pct_status": pct_status,
        "show_pct": effective_show,
        "canvas_h": canvas_h,
        "png_size": (2160, canvas_h * 2),
        "warnings": warnings,
        "excluded": excluded_names,
        "rows": rows,
    }


def write_json(path: Path, payload: dict) -> None:
    path.write_text(json.dumps(payload, indent=2) + "\n")
