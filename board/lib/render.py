TIEBREAK = "total desc → FG desc → name A–Z"


class MissingLogoError(FileNotFoundError):
    def __init__(self, missing: list[str]):
        self.missing = missing
        joined = ", ".join(missing)
        super().__init__(
            f"missing team logo(s): {joined}. "
            "Logos live in board/logos (committed). Refusing to render a board with blank logos."
        )


def logo_file(logo_dir: Path, abbr: str) -> Path:
    key = (abbr or "").strip().lower()
    direct = logo_dir / f"{key}.png"
    if direct.is_file():
        return direct
    alias = LOGO_ALIASES.get(key)
    if alias:
        aliased = logo_dir / f"{alias}.png"
        if aliased.is_file():
            return aliased
    return direct


def seg_label(count: int, blocked: int) -> str:
    if blocked:
        return f"{count} - {blocked} BLK"
    return str(count)


def week_of(kicker: dict, report_week: int, week_index: dict) -> int:
    return (
        kicker.get("week")
        or week_index.get(kicker.get("athleteId"))
        or week_index.get(kicker.get("kicker"))
        or report_week
    )


def week_index_from_misses(misses: list[dict] | None) -> dict:
    index: dict = {}
    for miss in misses or []:
        key_id = miss.get("athleteId")
        key_name = miss.get("kicker")
        week = miss.get("week") or 0
        if key_id:
            index[key_id] = max(index.get(key_id, 0), week)
        if key_name:
            index[key_name] = max(index.get(key_name, 0), week)
    return index


def suggested_post(season: int, week: int, rows: list[dict]) -> str:
    """Paste-ready caption. The owner posts this with the PNG; the tool does not."""
    lines = [
        f"{season} season miss leaders, thru Week {week}.",
        "Missed field goals and missed extra points. Blocked kicks count.",
        "",
    ]
    for row in rows:
        lines.append(f"{row['rank']}. {row['kicker']} ({row['teamAbbr']}) — {row['total']}")
    return "\n".join(lines).rstrip() + "\n"


def _row_html(row: dict, logo_src: str, max_total: int, pct: str | None, show_pct: bool, tag: str) -> str:
    width = 100.0 * row["total"] / max_total
    segments = []
    if row["fg"]:
        css = "seg fg with-blk" if row["fgBlocked"] else "seg fg"
        segments.append(
            f'<div class="{css}" style="flex:{row["fg"]}">{seg_label(row["fg"], row["fgBlocked"])}</div>'
        )
    if row["pat"]:
        css = "seg pat with-blk" if row["patBlocked"] else "seg pat"
        segments.append(
            f'<div class="{css}" style="flex:{row["pat"]}">{seg_label(row["pat"], row["patBlocked"])}</div>'
        )
    pct_html = ""
    if show_pct:
        pct_html = f'\n        <div class="pct">{pct or "&nbsp;"}</div>'
    tag_html = f'<span class="tag">{tag}</span>' if tag else ""
    return f"""    <div class="row">
      <div class="rank">{row["rank"]}</div>
      <img src="{logo_src}" alt="">
      <div class="meta">
        <div class="name"><span>{row["kicker"]}{tag_html}</span><span class="tot">{row["total"]}</span></div>{pct_html}
        <div class="bar-wrap"><div class="bar" style="width:{width:.2f}%">{"".join(segments)}</div></div>
      </div>
    </div>"""


