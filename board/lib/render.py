"""Render the season miss-leaders board: HTML, JSON summary, suggested post.

The graphic is the leaders-pct layout: 1080×1960 CSS (2160×3920 at scale 2)
with season percentages, or 1080×1680 (2160×3360) when percentages are off.
Field-goal segments are #1B4F8A. Extra-point segments are #8ECAE6.
In-bar block labels are `N - K BLK` with no parentheses.
"""

